# 1. Demonstration of break
print("Using break:")
for i in range(1, 6):
    if i == 3:
        break
    print(i)

# 2. Demonstration of continue
print("Using continue:")
for i in range(1, 6):
    if i == 3:
        continue
    print(i)

# 3. Demonstration of pass
print("Using pass:")
for i in range(1, 6):
    if i == 3:
        pass
    print(i)
