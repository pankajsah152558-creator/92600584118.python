
# Demonstration of different data types

a = 10
b = 3.14
c = "Hello Python"
d = True

print("Integer:", a, type(a))
print("Float:", b, type(b))
print("String:", c, type(c))
print("Boolean:", d, type(d))

# Demonstration of type casting
x = 5
y = float(x)
z = str(x)

print("Integer to Float:", y, type(y))
print("Integer to String:", z, type(z))

p = "25"
q = int(p)
print("String to Integer:", q, type(q))
